"""Previous-year UPSC questions (Prelims MCQs and Mains questions), matched to news stories by keyword.

The bank is data/pyq_prelims.json (about 3,800 Prelims questions 1995-2026 with answer keys, taken from the official UPSC question papers; subject and topic labels are our own, see pyq_taxonomy.py), data/pyq_bank.json (a few hand-entered Mains questions) plus anything an admin adds on the Past questions page. Nothing here is generated by AI:
every entry carries the exam, the year and (where known) the GS paper, and is shown with that tag. Entries were typed in by hand, so
the page always tells the reader to check wording and year at upsc.gov.in.
"""
import hashlib
import os
import json
import re
from pathlib import Path

from .ingest import now_iso

DATA = Path(__file__).resolve().parent.parent / "data"
BANK = DATA / "pyq_bank.json"
PRELIMS = DATA / "pyq_prelims.json"
_IDX = None  # in-memory keyword index, rebuilt after any change
GENERIC = set("""access aims policy capability dispute orders members agreement rates prices supply interest weight index consumer price department
administration government authority authorities declared declare provisions provision legislation implies related relation relations reference specified""".split())


def _key(q):
    return hashlib.sha1((q["exam"] + str(q["year"]) + re.sub(r"\W+", "", q["question"].lower())).encode()).hexdigest()[:16]


def clean(q):
    """Validate one entry. Returns a clean dict or raises ValueError."""
    exam = q.get("exam")
    if exam not in ("Prelims", "Mains"):
        raise ValueError("exam must be Prelims or Mains")
    year = q.get("year")
    if not (isinstance(year, int) and 1990 <= year <= 2100):
        raise ValueError("year must be a number like 2019")
    text = q.get("question")
    if not (isinstance(text, str) and 10 <= len(text) <= 2500):
        raise ValueError("question text missing")
    paper = q.get("paper") or None
    if paper not in (None, "GS1", "GS2", "GS3", "GS4", "CSAT", "Essay"):
        raise ValueError("paper must be GS1-GS4")
    kw = [k.strip().lower() for k in (q.get("keywords") or []) if isinstance(k, str) and k.strip()]
    if not kw:
        raise ValueError("at least one keyword is needed to match news")
    opts, ans = q.get("options"), q.get("answer_idx")
    if exam == "Prelims":
        if not (isinstance(opts, list) and len(opts) == 4 and all(isinstance(o, str) and o.strip() for o in opts)):
            raise ValueError("a Prelims question needs four options")
        if not (isinstance(ans, int) and 0 <= ans <= 3):
            raise ValueError("answer must be a, b, c or d")
    else:
        opts = ans = None
    ex = q.get("explanation")
    return {"exam": exam, "year": year, "paper": paper, "question": text.strip(), "options": opts, "answer_idx": ans,
            "explanation": ex.strip() if isinstance(ex, str) and ex.strip() else None, "keywords": kw}


def _insert(conn, raw, source):
    q = clean(raw)
    cur = conn.execute(
        """INSERT OR IGNORE INTO pyq(pkey,exam,year,paper,question,options,answer_idx,explanation,keywords,source,created_at,subject,topic) VALUES(?,?,?,?,?,?,?,?,?,?,?,?,?)""",
        (_key(q), q["exam"], q["year"], q["paper"], q["question"], json.dumps(q["options"]) if q["options"] else None, q["answer_idx"],
         q["explanation"], json.dumps(q["keywords"]), source, now_iso(), (raw.get("subject") or None), (raw.get("topic") or None)))
    return cur.rowcount


def sync_bank(conn, big=None):
    """Insert shipped entries that are not stored yet; remove shipped entries that are no longer in the files (safe on every start)."""
    global _IDX
    n, keep, loaded = 0, set(), []
    if big is None:
        big = not os.environ.get("UPSC_NO_PYQ")  # tests switch the 2 MB bank off to stay fast
    for path, source in ((PRELIMS, "pyq-pdf"), (BANK, "bank")) if big else ((BANK, "bank"),):
        try:
            items = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            continue
        loaded.append(source)
        for raw in items:
            try:
                q = clean(raw)
            except ValueError:
                continue
            keep.add(_key(q))
            n += _insert(conn, raw, source)
            if raw.get("subject"):  # keep labels in step with the shipped files
                conn.execute("UPDATE pyq SET subject=?, topic=? WHERE pkey=? AND (subject IS NOT ? OR topic IS NOT ?)",
                             (raw["subject"], raw.get("topic"), _key(q), raw["subject"], raw.get("topic")))
    if keep:
        for r in conn.execute(f"SELECT id, pkey FROM pyq WHERE source IN ({','.join('?' * len(loaded))})", loaded).fetchall():
            if r["pkey"] not in keep:
                conn.execute("DELETE FROM pyq WHERE id=?", (r["id"],))
    conn.commit()
    _IDX = None
    return n


def add(conn, raw, source="admin"):
    global _IDX
    rc = _insert(conn, raw, source)
    conn.commit()
    _IDX = None
    return rc


def parse_paste(text):
    """Parse the admin paste format (blocks separated by a line of ---). Returns (entries, errors)."""
    entries, errors = [], []
    for n, block in enumerate(re.split(r"^\s*-{3,}\s*$", text or "", flags=re.M), 1):
        if not block.strip():
            continue
        d, field, buf = {}, None, []
        for line in block.splitlines():
            m = re.match(r"^\s*(EXAM|YEAR|PAPER|KEYWORDS|Q|ANSWER|EXPLANATION)\s*:\s*(.*)$", line, flags=re.I) or \
                re.match(r"^\s*\(?([A-Da-d])\)\s+(.*)$", line)
            if m:
                if field is not None:
                    d[field] = "\n".join(buf).strip()
                field, buf = m.group(1).upper(), [m.group(2)]
            elif field is not None:
                buf.append(line)
        if field is not None:
            d[field] = "\n".join(buf).strip()
        try:
            exam = d.get("EXAM", "").strip().capitalize()
            raw = {"exam": exam, "year": int(re.sub(r"\D", "", d.get("YEAR", "")) or 0), "paper": (d.get("PAPER") or "").upper().replace(" ", "") or None,
                   "keywords": [k for k in re.split(r"[,;]", d.get("KEYWORDS", ""))], "question": d.get("Q", ""), "explanation": d.get("EXPLANATION")}
            if exam == "Prelims":
                raw["options"] = [d.get(x, "") for x in "ABCD"]
                a = d.get("ANSWER", "").strip().lower()[:1]
                raw["answer_idx"] = "abcd".index(a) if a and a in "abcd" else None
            entries.append(clean(raw))
        except (ValueError, KeyError) as e:
            errors.append(f"Block {n}: {e}")
    return entries, errors


def _row(r):
    d = dict(r)
    d["options"] = json.loads(r["options"]) if r["options"] else None
    d["keywords"] = json.loads(r["keywords"])
    d["tag"] = tag(d)
    return d


def tag(q):
    """The label printed under a question, e.g. 'UPSC Prelims 2019' or 'UPSC Mains 2018, GS II'."""
    s = f"UPSC {q['exam']} {q['year']}"
    if q["exam"] == "Mains" and q.get("paper") in ("GS1", "GS2", "GS3", "GS4"):
        s += ", GS " + {"GS1": "I", "GS2": "II", "GS3": "III", "GS4": "IV"}[q["paper"]]
    return s


def _index(conn):
    """keyword -> question ids, plus document frequencies, built once and cached."""
    global _IDX
    if _IDX is None:
        tok, phr, df, meta = {}, [], {}, {}
        rows = conn.execute("SELECT id, exam, year, source, keywords FROM pyq").fetchall()
        for r in rows:
            kws = json.loads(r["keywords"])
            meta[r["id"]] = (r["exam"], r["year"], r["source"] in ("pyq-pdf",), kws)
            for k in set(kws):
                df[k] = df.get(k, 0) + 1
                if " " in k:
                    phr.append((k, r["id"]))
                else:
                    tok.setdefault(k, []).append(r["id"])
        _IDX = {"tok": tok, "phr": phr, "df": df, "meta": meta, "n": max(1, len(rows))}
    return _IDX


def match(conn, text, limit=3, exam=None):
    """Questions that fit `text` (headline + notes), best first.
    Bulk questions (from the PDF) carry auto-picked rare words: they need two of them (or one very rare word, or a named phrase) so that
    an unrelated story does not pull in a question. Hand-entered questions match on any one of their keywords."""
    import math
    ix = _index(conn)
    low = " " + re.sub(r"\s+", " ", (text or "").lower()) + " "
    head = (text or "").split("\n", 1)[0].lower()  # the story headline is the first line of `text`
    words = set(re.findall(r"[a-z]{4,}", low))
    hit = {}
    for w in words:
        for qid in ix["tok"].get(w, ()):
            hit.setdefault(qid, []).append(w)
    for k, qid in ix["phr"]:
        if k in low:
            hit.setdefault(qid, []).append(k)
    scored = []
    for qid, ks in hit.items():
        ex, year, bulk, _ = ix["meta"][qid]
        if exam and ex != exam:
            continue
        # a phrase and its own words are one idea ("prime minister" = prime + minister), not three
        ks = [k for k in ks if " " in k or not any(" " in p and k in p.split() for p in ks)]
        idf = [math.log(ix["n"] / max(1, ix["df"][k])) for k in ks]
        score = sum(idf)
        if bulk:
            anchor = any(ix["df"][k] <= 12 and len(k) >= 6 and k not in GENERIC for k in ks)
            unique = any(ix["df"][k] == 1 and k not in GENERIC and ((len(k) >= 9 and len(ks) >= 2) or (len(k) >= 11 and " " not in k and k in head) or (" " in k and any(ch.isdigit() for ch in k))) for k in ks)
            if not (unique or (anchor and len(ks) >= 2 and score >= 16) or (anchor and len(ks) >= 3 and score >= 12)):
                continue
            if unique:
                score += 40
        scored.append((score, year, qid))
    scored.sort(key=lambda x: (-x[0], -x[1]))
    top = [qid for _, _, qid in scored[:limit]]
    if not top:
        return []
    rows = {r["id"]: r for r in conn.execute(f"SELECT * FROM pyq WHERE id IN ({','.join('?' * len(top))})", top)}
    return [_row(rows[i]) for i in top]


def subjects(conn):
    return [(r[0], r[1]) for r in conn.execute("SELECT subject, COUNT(*) FROM pyq WHERE subject IS NOT NULL GROUP BY subject ORDER BY 2 DESC")]


def browse(conn, subject="", year=0, q="", offset=0, limit=20):
    sql, args = " FROM pyq WHERE exam='Prelims'", []
    if subject:
        sql += " AND subject=?"; args.append(subject)
    if year:
        sql += " AND year=?"; args.append(year)
    if q:
        sql += " AND (question LIKE ? ESCAPE '\\' OR options LIKE ? ESCAPE '\\')"
        like = "%" + q.replace("\\", "\\\\").replace("%", "\\%").replace("_", "\\_") + "%"
        args += [like, like]
    total = conn.execute("SELECT COUNT(*)" + sql, args).fetchone()[0]
    rows = conn.execute("SELECT *" + sql + " ORDER BY year DESC, id LIMIT ? OFFSET ?", args + [limit, offset]).fetchall()
    return total, [_row(r) for r in rows]


def sample_prelims(conn, n, subject="", y0=0, y1=3000, seed=""):
    import random
    sql, args = "SELECT * FROM pyq WHERE exam='Prelims' AND year>=? AND year<=?", [y0, y1]
    if subject:
        sql += " AND subject=?"; args.append(subject)
    rows = conn.execute(sql, args).fetchall()
    random.Random(seed).shuffle(rows)
    return [_row(r) for r in rows[:n]]


def event_text(conn, event_id):
    e = conn.execute("SELECT headline FROM news_events WHERE id=?", (event_id,)).fetchone()
    a = conn.execute("SELECT summary, key_points, prelims FROM ai_notes WHERE event_id=?", (event_id,)).fetchone()
    parts = [e["headline"] if e else ""]
    if a:
        parts += [a["summary"] or "", a["key_points"] or "", a["prelims"] or ""]
    sn = conn.execute("SELECT snippet FROM source_items WHERE event_id=?", (event_id,)).fetchall()
    parts += [s["snippet"] or "" for s in sn]
    return parts[0] + "\n" + " ".join(parts[1:])


def for_event(conn, event_id, limit=3):
    return match(conn, event_text(conn, event_id), limit)


def count(conn):
    return conn.execute("SELECT COUNT(*) FROM pyq").fetchone()[0]
